package com.ngapp.quottie.authors.list

import app.cash.turbine.test
import com.ngapp.quottie.authors.list.fake.FakeAuthorRepository
import com.ngapp.quottie.authors.list.state.AuthorsUiState
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.test.StandardTestDispatcher
import kotlinx.coroutines.test.resetMain
import kotlinx.coroutines.test.runTest
import kotlinx.coroutines.test.setMain
import kotlin.test.AfterTest
import kotlin.test.BeforeTest
import kotlin.test.Test
import kotlin.test.assertIs

class AuthorsViewModelTest {

    private val testDispatcher = StandardTestDispatcher()

    @BeforeTest
    fun setUp() {
        Dispatchers.setMain(testDispatcher)
    }

    @AfterTest
    fun tearDown() {
        Dispatchers.resetMain()
    }

    @Test
    fun uiState_startsAsLoadingThenBecomesSuccess() = runTest(testDispatcher) {
        val viewModel = AuthorsViewModel(FakeAuthorRepository())

        viewModel.uiState.test {
            assertIs<AuthorsUiState.Loading>(awaitItem())
            assertIs<AuthorsUiState.Success>(awaitItem())
        }
    }
}
